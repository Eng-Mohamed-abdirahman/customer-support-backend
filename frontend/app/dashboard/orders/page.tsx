"use client"

import { RefreshCw, ShoppingCart } from "lucide-react"
import { useCallback, useEffect, useState } from "react"

import { Button } from "@/components/ui/button"
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card"

import { Skeleton } from "@/components/ui/skeleton"
import { listOrders, updateOrderStatus } from "@/services/order.service"
import type { Order, OrderStatus } from "@/types/order"

const statusColors: Record<OrderStatus, string> = {
  pending: "bg-yellow-500/10 text-yellow-500",
  confirmed: "bg-blue-500/10 text-blue-500",
  processing: "bg-purple-500/10 text-purple-500",
  completed: "bg-green-500/10 text-green-500",
  cancelled: "bg-red-500/10 text-red-500",
}

const formatDate = (dateStr: string) => {
  return new Date(dateStr).toLocaleString(undefined, {
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
  })
}

export default function OrdersPage() {
  const [orders, setOrders] = useState<Order[]>([])
  const [isLoading, setIsLoading] = useState(true)
  const [isRefreshing, setIsRefreshing] = useState(false)

  const loadData = useCallback(async (refresh = false) => {
    if (refresh) setIsRefreshing(true)
    else setIsLoading(true)

    try {
      const result = await listOrders()
      setOrders(result.data)
    } catch (error) {
      console.error("Failed to fetch orders", error)
    } finally {
      setIsLoading(false)
      setIsRefreshing(false)
    }
  }, [])

  useEffect(() => {
    void loadData()
  }, [loadData])

  const handleStatusChange = async (orderId: string, newStatus: OrderStatus) => {
    try {
      const res = await updateOrderStatus(orderId, newStatus)
      setOrders((prev) =>
        prev.map((order) => (order._id === orderId ? res.data : order))
      )
    } catch (error) {
      console.error("Failed to update status", error)
    }
  }

  return (
    <div className="space-y-6">
      <header className="flex items-center justify-between">
        <div>
          <h1 className="text-3xl font-semibold tracking-tight text-foreground">Orders</h1>
          <p className="mt-1 text-sm text-muted-foreground">
            View and manage customer orders placed via AI.
          </p>
        </div>
        <Button
          variant="outline"
          className="h-9 gap-2"
          onClick={() => void loadData(true)}
          disabled={isLoading || isRefreshing}
        >
          <RefreshCw className={`size-4 ${isRefreshing ? "animate-spin" : ""}`} />
          Refresh
        </Button>
      </header>

      <Card className="border-border/70 bg-card/95">
        <CardHeader className="border-b border-border/60 pb-4">
          <div className="flex items-center gap-2">
            <ShoppingCart className="size-5 text-primary" />
            <div>
              <CardTitle className="text-lg">Recent Orders</CardTitle>
              <CardDescription>All orders generated by your AI assistants</CardDescription>
            </div>
          </div>
        </CardHeader>
        <CardContent className="p-0">
          {isLoading ? (
            <div className="space-y-4 p-6">
              {[1, 2, 3].map((i) => (
                <Skeleton key={i} className="h-16 w-full" />
              ))}
            </div>
          ) : orders.length === 0 ? (
            <div className="py-16 text-center">
              <ShoppingCart className="mx-auto size-8 text-muted-foreground/50" />
              <p className="mt-4 text-sm font-medium text-foreground">No orders yet</p>
              <p className="mt-1 text-xs text-muted-foreground">
                When the AI processes an order, it will appear here.
              </p>
            </div>
          ) : (
            <div className="overflow-x-auto">
              <table className="w-full min-w-[800px] text-left text-sm">
                <thead>
                  <tr className="border-b border-border/50 bg-muted/40">
                    <th className="px-6 py-3 font-medium text-muted-foreground">Date</th>
                    <th className="px-6 py-3 font-medium text-muted-foreground">Customer</th>
                    <th className="px-6 py-3 font-medium text-muted-foreground">Order Item</th>
                    <th className="px-6 py-3 font-medium text-muted-foreground">Qty</th>
                    <th className="px-6 py-3 font-medium text-muted-foreground">Status</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-border/50">
                  {orders.map((order) => (
                    <tr key={order._id} className="transition-colors hover:bg-muted/20">
                      <td className="whitespace-nowrap px-6 py-4 text-muted-foreground">
                        {formatDate(order.createdAt)}
                      </td>
                      <td className="px-6 py-4">
                        <div className="font-medium text-foreground">{order.customerName}</div>
                        <div className="text-xs text-muted-foreground">{order.phone}</div>
                      </td>
                      <td className="px-6 py-4">
                        <div className="font-medium text-foreground">{order.orderName}</div>
                        {order.notes && (
                          <div className="text-xs text-muted-foreground">Note: {order.notes}</div>
                        )}
                      </td>
                      <td className="px-6 py-4 text-foreground">{order.quantity}</td>
                      <td className="px-6 py-4">
                        <select
                          value={order.status}
                          onChange={(e) => handleStatusChange(order._id, e.target.value as OrderStatus)}
                          className={`h-8 w-[130px] rounded-md border border-border/50 px-2 text-xs font-semibold capitalize tracking-wide ${
                            statusColors[order.status]
                          }`}
                        >
                          <option value="pending">Pending</option>
                          <option value="confirmed">Confirmed</option>
                          <option value="processing">Processing</option>
                          <option value="completed">Completed</option>
                          <option value="cancelled">Cancelled</option>
                        </select>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  )
}
